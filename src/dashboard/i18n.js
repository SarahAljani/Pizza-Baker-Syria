export function translate(language, key, vars) {
  let text = dashboardTranslations[language]?.[key] ?? dashboardTranslations.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, v);
    }
  }
  return text;
}
